"""E27: conservative mode against re-worded corrections, on a HELD-OUT family.

E25 showed that the revision ledger is only as good as its English cue words:
on corrections re-worded by gemma3:27b without those words, Relay shipped
superseded constraints without their replacements.  Conservative mode
(``state/schema.py: conservative_updates``) ships uncued turns that could carry
a correction verbatim and marks the task statement's constraints
non-authoritative.  It was developed while looking at the gemma family, which
is therefore a *development* set.  The *held-out* family was generated by a
different model family (mistral-small3.1:24b), with different registers and
seeds (``gen_e27_heldout_paraphrases.py``), and was scored only after the
conservative-mode code was frozen (AUDIT H.3 records the SHA-256 of
``src/state/schema.py`` at freeze time).

Scored with the E14b metrics on each corpus:

  * live-state recall (revised goal, active constraint, corrected value, open
    question) and per-field recall;
  * superseded state shipped without its replacement;
  * the budget the block uses (resume tokens) and how often conservative mode
    fires.

And its cost on the real corpus (the 184 Who&When trajectories, the E1 handoff
positions, watch budget): future-relevance recall and block tokens with
conservative mode off and on, paired by handoff.

Corpora: ``template`` (the generator's own wording), ``dev-natural`` and
``dev-disjoint`` (gemma rewrites), ``heldout-natural`` and ``heldout-disjoint``
(mistral rewrites).  Episodes with any failed rewrite are dropped from that
corpus only.  The rewrites are LLM-generated, not written by people.
"""
import hashlib
import json
import os
import sys
import time
from collections import defaultdict

import numpy as np

sys.path.insert(0, os.path.dirname(__file__))
from explib import (load_all, sample_positions, real_fidelity, boot_ci,  # noqa
                    policy_budget, RES)
from stats import compare                                               # noqa
from state.schema import Distiller                                      # noqa
from synth.oos import generate_oos                                      # noqa
from traces.anchors import AnchorIndex, norm_text                       # noqa
from traces.parser import est_tokens                                    # noqa
from policies.policies import POLICIES                                  # noqa

OUT = os.path.join(RES, "e27_conservative.json")
SEEDS = [0, 1, 2, 3, 4]
DST = "watch"
POLS = ["full", "trunc25", "recency", "typed-recency", "randdrop", "relay",
        "relay-conservative", "restart"]
SCHEMA = os.path.join(os.path.dirname(__file__), "..", "src", "state",
                      "schema.py")


def reworded(para_path, cond):
    para = json.load(open(para_path))
    eps, dropped = [], 0
    for e in generate_oos(120, seed=7):
        rec = para["episodes"].get(f"{e.eid}|{cond}")
        if rec is None or any(it["paraphrase"] is None
                              for it in rec["items"]):
            dropped += 1
            continue
        for it in rec["items"]:
            s = e.steps[it["step"]]
            assert it["replace"] in s.content, (e.eid, it["slot"])
            s.content = s.content.replace(it["replace"], it["paraphrase"])
            s.tokens = est_tokens(s.content)
        eps.append(e)
    return eps, dropped, para.get("model")


def score_oos(eps):
    trajs = [e.to_trajectory() for e in eps]
    idx = AnchorIndex.__new__(AnchorIndex)
    idx.df, idx.n_trajs, idx.df_cut = {}, len(trajs), len(trajs)
    dist = {"relay": Distiller(idx),
            "relay-conservative": Distiller(idx, conservative=True)}
    live = defaultdict(list)
    per_field = {p: defaultdict(list) for p in POLS}
    stale = defaultdict(list)
    tokens = defaultdict(list)
    fired = []
    for e, traj in zip(eps, trajs):
        for s in SEEDS:
            for k in sample_positions(e.n, e.eid, s):
                if k >= e.n:
                    continue
                probes, negs = e.oos_probes(k), e.oos_negatives(k)
                if not probes:
                    continue
                for p in POLS:
                    if p.startswith("relay"):
                        o = POLICIES["relay"](traj, k, DST, distiller=dist[p],
                                              budget=policy_budget("relay",
                                                                   DST))
                    else:
                        o = POLICIES[p](traj, k, DST, seed=s,
                                        budget=policy_budget(p, DST))
                    h = norm_text(o.resume_text)
                    tokens[p].append(o.tokens_resume)
                    if p == "relay-conservative":
                        fired.append(float("== LATER STATEMENTS" in
                                           o.resume_text))
                    hits = tot = 0
                    present = {}
                    for f, targets in probes.items():
                        ok = all(norm_text(str(x)) in h for x in targets if x)
                        present[f] = ok
                        per_field[p][f].append(float(ok))
                        hits += ok
                        tot += 1
                    live[p].append(hits / tot if tot else 1.0)
                    bad = n = 0
                    for sname, lname in (("stale_goal", "revised_goal"),
                                         ("stale_constraint",
                                          "active_constraint"),
                                         ("stale_value", "corrected_value")):
                        if sname not in negs or lname not in probes:
                            continue
                        st = all(norm_text(str(x)) in h
                                 for x in negs[sname] if x)
                        n += 1
                        bad += int(st and not present.get(lname, False))
                    if n:
                        stale[p].append(bad / n)
    return {
        "n_episodes": len(eps), "n_handoffs": len(live["relay"]),
        "live_state_recall": {p: [round(x, 4) for x in boot_ci(live[p])]
                              for p in POLS},
        "superseded_shipped_alone": {
            p: round(float(np.mean(stale[p])), 4) if stale[p] else None
            for p in POLS},
        "per_field": {p: {f: round(float(np.mean(v)), 4)
                          for f, v in sorted(d.items())}
                      for p, d in per_field.items()},
        "mean_resume_tokens": {p: round(float(np.mean(tokens[p])), 1)
                               for p in POLS},
        "conservative_fired": round(float(np.mean(fired)), 4) if fired
        else None,
        "paired_live_vs_relay_conservative": compare(
            live["relay-conservative"],
            {b: live[b] for b in ("relay", "full", "recency", "randdrop")}),
    }


def real_cost(trajs, idx):
    base, cons = Distiller(idx), Distiller(idx, conservative=True)
    rb, rc, sb, sc, tb, tc, fired, added = [], [], [], [], [], [], [], []
    for t in trajs:
        for seed in SEEDS:
            for k in sample_positions(len(t.steps), t.tid, seed):
                if k >= len(t.steps):
                    continue
                A = idx.future_relevant(t, k)
                ob = POLICIES["relay"](t, k, DST, distiller=base,
                                       budget=policy_budget("relay", DST))
                oc = POLICIES["relay"](t, k, DST, distiller=cons,
                                       budget=policy_budget("relay", DST))
                r1, s1, _ = real_fidelity(idx, t, k, ob.resume_text, anchors=A)
                r2, s2, _ = real_fidelity(idx, t, k, oc.resume_text, anchors=A)
                rb.append(r1)
                rc.append(r2)
                sb.append(s1)
                sc.append(s2)
                tb.append(ob.tokens_resume)
                tc.append(oc.tokens_resume)
                fired.append(float("== LATER STATEMENTS" in oc.resume_text))
    return {"n_handoffs": len(rb),
            "recall_base": [round(x, 4) for x in boot_ci(rb)],
            "recall_conservative": [round(x, 4) for x in boot_ci(rc)],
            "recall_strict_base": round(float(np.mean(sb)), 4),
            "recall_strict_conservative": round(float(np.mean(sc)), 4),
            "tokens_base": round(float(np.mean(tb)), 1),
            "tokens_conservative": round(float(np.mean(tc)), 1),
            "fired": round(float(np.mean(fired)), 4),
            "paired": compare(rc, {"base": rb})}


def run():
    t0 = time.time()
    only = os.environ.get("RELAY_E27_ONLY", "")      # e.g. "dev" while developing
    out = {"schema_sha256": hashlib.sha256(open(SCHEMA, "rb").read())
           .hexdigest(), "corpora": {}}
    corpora = [("template", None, None)]
    corpora += [("dev-natural", "e25_paraphrases.json", "natural"),
                ("dev-disjoint", "e25_paraphrases.json", "disjoint")]
    if only != "dev":
        corpora += [("heldout-natural", "e27_heldout_paraphrases.json",
                     "natural"),
                    ("heldout-disjoint", "e27_heldout_paraphrases.json",
                     "disjoint")]
    for name, path, cond in corpora:
        if path is None:
            eps, dropped, model = generate_oos(120, seed=7), 0, "template"
        else:
            eps, dropped, model = reworded(os.path.join(RES, path), cond)
        res = score_oos(eps)
        res.update({"dropped": dropped, "generator": model})
        out["corpora"][name] = res
        L, S = res["live_state_recall"], res["superseded_shipped_alone"]
        print(f"[{name}] n={res['n_episodes']} fired={res['conservative_fired']}",
              flush=True)
        for p in POLS:
            print(f"   {p:20s} live={L[p][0]:.3f} stale={S[p]} "
                  f"tok={res['mean_resume_tokens'][p]}", flush=True)
        print("   relay per-field", res["per_field"]["relay"])
        print("   cons  per-field", res["per_field"]["relay-conservative"])
    if only != "dev":
        trajs, idx, *_ = load_all()
        out["real_cost"] = real_cost(trajs, idx)
        print("real cost:", json.dumps({k: v for k, v in
                                        out["real_cost"].items()
                                        if k != "paired"}), flush=True)
    out["runtime_s"] = round(time.time() - t0, 1)
    path = OUT if only != "dev" else OUT.replace(".json", "_devonly.json")
    json.dump(out, open(path, "w"), indent=1)
    print("->", path, out["runtime_s"], "s")


if __name__ == "__main__":
    run()
